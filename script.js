// Helper to shuffle
// Fisher-Yates (Knuth) Shuffle Algorithm - High-Performance & Truly Unbiased
function shuffle(array) {
    let currentIndex = array.length, randomIndex;
    while (currentIndex != 0) {
        randomIndex = Math.floor(Math.random() * currentIndex);
        currentIndex--;
        [array[currentIndex], array[randomIndex]] = [array[randomIndex], array[currentIndex]];
    }
    return array;
}

// Seeded Pseudo-Random Generator (Mulberry32) for Student-Specific Consistent Randomization
function createSeededRNG(seedStr) {
    let hash = 0;
    for (let i = 0; i < seedStr.length; i++) {
        hash = (hash << 5) - hash + seedStr.charCodeAt(i);
        hash |= 0;
    }
    return function () {
        hash = (hash + 0x6D2B79F5) | 0;
        let t = Math.imul(hash ^ (hash >>> 15), 1 | hash);
        t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}

// Fisher-Yates shuffle using Seeded RNG or pure Math.random
function shuffleArrayWithRNG(array, rngFn) {
    const arr = array.slice();
    const getRandom = rngFn || Math.random;
    for (let i = arr.length - 1; i > 0; i--) {
        const j = Math.floor(getRandom() * (i + 1));
        [arr[i], arr[j]] = [arr[j], arr[i]];
    }
    return arr;
}

