function cleanDecimal(val, maxDec = 8) {
    if (typeof val !== 'number' || isNaN(val)) return String(val);
    if (Number.isInteger(val)) return String(val);
    const fixed = val.toFixed(maxDec);
    const clean = fixed.replace(/\.?0+$/, '');
    return clean;
}

function autoGenerateDistractors(correct) {
    const n = parseFloat(correct);
    if (isNaN(n)) return [];
    const mag = Math.abs(n);
    let step;
    let dec = 0;
    if (String(correct).includes('.')) {
        dec = String(correct).split('.')[1].length;
        step = Math.pow(10, -dec);
    } else {
        step = mag < 10 ? 1 : mag < 50 ? 5 : mag < 200 ? 10 : 25;
    }
    const candidates = [
        n + step,
        n - step,
        n + step * 2,
        n - step * 2,
        n + step * 3,
        n - step * 3
    ].filter(v => v !== n && v >= 0);
    const unique = [...new Set(candidates)].slice(0, 3);
    return unique.map(v => cleanDecimal(v, Math.max(dec, 4)));
}

function resolveDynamicQuestion(q, studentSeedKey, qIndex = 0) {
    if (!q || (!q.isDynamic && !q.variables && !q.variable_formulas)) {
        return q;
    }

    try {
        // Generate a fresh random increment (1 to 20) on every single attempt
        const inc = Math.floor(Math.random() * 20) + 1;

        const variables = q.variables || {};
        const varFormulas = q.variable_formulas || {};
        const base = { ...(q.base_values || {}) };
        const values = { ...base };

        if (typeof variables === 'object' && Object.keys(variables).length > 0) {
            for (const [k, cfg] of Object.entries(variables)) {
                if (typeof cfg === 'object' && cfg !== null) {
                    const b = Number(cfg.base !== undefined ? cfg.base : (cfg.min !== undefined ? cfg.min : 0));
                    const s = Number(cfg.step !== undefined ? cfg.step : 1);
                    values[k] = b + (inc * s);
                } else if (typeof cfg === 'number') {
                    values[k] = cfg + inc;
                }
            }
        }

        if (typeof varFormulas === 'object' && Object.keys(varFormulas).length > 0) {
            for (const [k, expr] of Object.entries(varFormulas)) {
                try {
                    values[k] = eval(expr.replace(/\binc\b/g, inc).replace(/\b([A-Z]+)\b/g, (m, v) => base[v] ?? m));
                } catch(e) {
                    values[k] = base[k] || 0;
                }
            }
        }

        let computedAnswer = q.answer;
        if (q.formula_logic) {
            try {
                let code = String(q.formula_logic).trim();
                let fnBody = code;
                if (!code.includes('return')) {
                    if (code.includes(';')) {
                        const parts = code.split(';').map(p => p.trim()).filter(Boolean);
                        const lastPart = parts.pop();
                        fnBody = parts.join(';\n') + ';\nreturn (' + lastPart + ');';
                    } else {
                        fnBody = 'return (' + code + ');';
                    }
                }
                const fn = new Function(...Object.keys(values), fnBody);
                const raw = fn(...Object.values(values));
                if (typeof raw === 'number' && !isNaN(raw)) {
                    if (q.format_rule !== undefined && q.format_rule !== null) {
                        const fmt = parseInt(q.format_rule);
                        computedAnswer = parseFloat(raw.toFixed(fmt)).toString() + (q.suffix || '');
                    } else {
                        computedAnswer = cleanDecimal(raw, 8) + (q.suffix || '');
                    }
                } else if (raw !== undefined && raw !== null) {
                    computedAnswer = String(raw) + (q.suffix || '');
                }
            } catch (err) {
                console.warn("Formula evaluation error:", err);
            }
        }

        const template = q.template || q.q || q.question || '';
        const filledQ = template.replace(/\{([A-Z0-9_]+)\}/gi, (match, key) => {
            return values[key] !== undefined ? values[key] : match;
        });

        // Generate matching options around the computed answer
        let wrongOpts = [];
        if (Array.isArray(q.distractor_rules) && q.distractor_rules.length > 0) {
            const ANS = parseFloat(computedAnswer);
            wrongOpts = q.distractor_rules.map(rule => {
                try {
                    const fnRule = new Function('ANS', ...Object.keys(values), 'return (' + rule + ');');
                    const val = fnRule(ANS, ...Object.values(values));
                    if (val !== undefined && val !== null && !isNaN(val)) {
                        const cleanVal = typeof val === 'number' ? cleanDecimal(val, 8) : val;
                        return String(cleanVal) + (q.suffix || '');
                    }
                    return null;
                } catch(e) {
                    try {
                        const val = eval(String(rule).replace(/\bANS\b/g, ANS));
                        return String(val) + (q.suffix || '');
                    } catch(err2) {
                        return null;
                    }
                }
            }).filter(v => v !== null && v !== String(computedAnswer));
        }

        if (wrongOpts.length < 3) {
            const fallbackWrong = autoGenerateDistractors(computedAnswer);
            fallbackWrong.forEach(opt => {
                if (!wrongOpts.includes(opt) && opt !== String(computedAnswer)) {
                    wrongOpts.push(opt + (q.suffix || ''));
                }
            });
        }

        // Combine computed correct answer and 3 wrong options
        let allOptions = [String(computedAnswer), ...wrongOpts.slice(0, 3)];
        
        // If still fewer than 4 options, pad from original options
        if (allOptions.length < 4 && Array.isArray(q.options)) {
            q.options.forEach(opt => {
                if (allOptions.length < 4 && !allOptions.includes(String(opt))) {
                    allOptions.push(String(opt));
                }
            });
        }

        // Shuffle options so correct answer is at a random position
        for (let i = allOptions.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [allOptions[i], allOptions[j]] = [allOptions[j], allOptions[i]];
        }

        return {
            ...q,
            q: filledQ,
            question: filledQ,
            options: allOptions,
            answer: String(computedAnswer),
            _isDynamicResolved: true
        };
    } catch (err) {
        console.error("Error resolving dynamic question:", err);
        return q;
    }
}

function shuffleExamQuestionsAndOptions(rawQuestions, studentSeed) {
    if (!Array.isArray(rawQuestions) || rawQuestions.length === 0) return [];

    const mainRng = studentSeed ? createSeededRNG(studentSeed) : null;

    // Step 1: Deep copy and shuffle the question order
    const shuffledQuestions = shuffleArrayWithRNG(rawQuestions, mainRng);

    // Step 2: Shuffle option choices (A, B, C, D) for each question independently
    return shuffledQuestions.map((q, idx) => {
        let qCopy = JSON.parse(JSON.stringify(q));
        qCopy = resolveDynamicQuestion(qCopy, studentSeed, idx);
        if (Array.isArray(qCopy.options) && qCopy.options.length > 0) {
            const optionSeed = studentSeed ? `${studentSeed}_opt_${idx}_${qCopy.id || qCopy.q || idx}` : null;
            const optionRng = optionSeed ? createSeededRNG(optionSeed) : null;
            qCopy.options = shuffleArrayWithRNG(qCopy.options, optionRng);
        }
        return qCopy;
    });
}

